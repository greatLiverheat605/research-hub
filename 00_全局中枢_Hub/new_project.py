#!/usr/bin/env python3
"""
00_全局中枢_Hub/new_project.py
一键在 01_在研课题_Projects/ 下创建标准化、物理隔离的新科研课题舱，
并自动登记到 00_全局中枢_Hub/WORKSPACE_INDEX.md。
"""

import argparse
import datetime
import re
import shutil
import sys
from pathlib import Path


HUB_DIR = Path(__file__).resolve().parent
EXCHANGE_ROOT = HUB_DIR.parent
TEMPLATE_DIR = HUB_DIR / "_project_template"
PROJECTS_DIR = EXCHANGE_ROOT / "01_在研课题_Projects"
INDEX_PATH = HUB_DIR / "WORKSPACE_INDEX.md"
MODELS_TOML = HUB_DIR / "models.toml"


def _validate_name(name: str) -> str:
    """Validate project folder name to avoid path traversal or illegal characters."""
    cleaned = name.strip()
    if not cleaned or "/" in cleaned or "\\" in cleaned or cleaned in (".", ".."):
        raise ValueError(f"非法的课题文件夹名称：'{name}'")
    if cleaned.startswith("."):
        raise ValueError(f"课题文件夹名称不能以 '.' 开头：'{name}'")
    return cleaned


def _render_templates(target_dir: Path, project_name: str, created_date: str) -> None:
    """Replace {{PROJECT_NAME}} and {{CREATED_DATE}} placeholders in copied markdown files."""
    for md_file in target_dir.rglob("*.md"):
        text = md_file.read_text(encoding="utf-8")
        rendered = text.replace("{{PROJECT_NAME}}", project_name).replace("{{CREATED_DATE}}", created_date)
        md_file.write_text(rendered, encoding="utf-8")


def _append_workspace_index(project_name: str, goal: str, created_date: str) -> None:
    """Register the new project row in WORKSPACE_INDEX.md if not already listed."""
    if not INDEX_PATH.exists():
        return
    content = INDEX_PATH.read_text(encoding="utf-8")
    if f"`{project_name}`" in content:
        return
    safe_goal = goal.replace("|", "｜").strip() or "待定（新立项）"
    row = f"| `{project_name}` | 🟡 立项中 | {safe_goal} | `{created_date}` | `01_在研课题_Projects/{project_name}/` |"
    lines = content.rstrip("\n").splitlines()
    insert_idx = len(lines)
    for idx, line in enumerate(lines):
        s = line.strip()
        if s == "---" or s.startswith("## 二、"):
            insert_idx = idx
            break
    while insert_idx > 0 and not lines[insert_idx - 1].strip():
        insert_idx -= 1
    lines.insert(insert_idx, row)
    INDEX_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _sync_shell_project_aliases() -> None:
    """Regenerate ~/.config/research_hub/projects.zsh with p01/p02/... and `p` helper."""
    env_dir = Path.home() / ".config" / "research_hub"
    env_dir.mkdir(parents=True, exist_ok=True)
    zsh_file = env_dir / "projects.zsh"
    lines = [
        "# Auto-generated by 00_全局中枢_Hub/new_project.py. Do not edit manually.",
    ]
    if PROJECTS_DIR.is_dir():
        for proj in sorted(PROJECTS_DIR.iterdir(), key=lambda x: x.name):
            if not proj.is_dir() or proj.name.startswith("."):
                continue
            prefix = proj.name.split("_", 1)[0].lower()
            if re.fullmatch(r"[a-z0-9-]+", prefix):
                lines.append(f"alias {prefix}='cd \"{proj}\"'")
    lines.extend([
        "",
        "p() {",
        "  local q=\"${1:-}\"",
        f"  local root=\"{PROJECTS_DIR}\"",
        "  if [[ -z \"$q\" ]]; then ls -1 \"$root\"; return 0; fi",
        "  local match",
        "  match=$(find \"$root\" -maxdepth 1 -mindepth 1 -type d -iname \"*${q}*\" | sort | head -n 1)",
        "  if [[ -n \"$match\" ]]; then cd \"$match\" && pwd; else echo \"未找到匹配课题: $q\"; return 1; fi",
        "}",
    ])
    zsh_file.write_text("\n".join(lines) + "\n", encoding="utf-8")


def _set_active_project(project_name: str) -> None:
    """Update active_project in models.toml when --activate is passed."""
    if not MODELS_TOML.exists():
        return
    text = MODELS_TOML.read_text(encoding="utf-8")
    updated, count = re.subn(
        r'(?m)^active_project\s*=\s*"[^"]*"',
        f'active_project = "{project_name}"',
        text,
        count=1,
    )
    if count:
        MODELS_TOML.write_text(updated, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="一键在 01_在研课题_Projects/ 下创建独立科研课题舱并登记索引"
    )
    parser.add_argument("name", help="新课题目录名（建议编号前缀，例如 P02_单细胞图谱插补）")
    parser.add_argument("--goal", default="", help="一句话研究目标说明（写入 WORKSPACE_INDEX.md）")
    parser.add_argument("--activate", action="store_true", help="同时将其设为 models.toml 的默认 active_project")
    args = parser.parse_args()

    try:
        project_name = _validate_name(args.name)
    except ValueError as err:
        print(f"[ERROR] {err}", file=sys.stderr)
        return 1

    if not TEMPLATE_DIR.is_dir():
        print(f"[ERROR] 缺少模板目录：{TEMPLATE_DIR}", file=sys.stderr)
        return 1

    target_dir = PROJECTS_DIR / project_name
    if target_dir.exists():
        print(f"[ERROR] 目标课题已存在：{target_dir}", file=sys.stderr)
        return 1

    created_date = datetime.datetime.now().strftime("%Y-%m-%d")
    shutil.copytree(TEMPLATE_DIR, target_dir)
    _render_templates(target_dir, project_name, created_date)
    _append_workspace_index(project_name, args.goal, created_date)
    _sync_shell_project_aliases()

    if args.activate:
        _set_active_project(project_name)

    print(f"[ResearchHub] 已成功创建新课题舱：{target_dir}")
    print(f"[ResearchHub] 虚拟机内 Claude 路径：/Volumes/My Shared Files/ClaudeShield-Exchange/01_在研课题_Projects/{project_name}/")
    if args.activate:
        print(f"[ResearchHub] 已将默认 active_project 切换为：{project_name}")
    print("下一步：在虚拟机 Claude Desktop 新建对应 Project，并在其指令中锁定上述客机路径即可。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
